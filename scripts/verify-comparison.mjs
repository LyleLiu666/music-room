import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const output = new URL('../test-results/comparison/', import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--autoplay-policy=no-user-gesture-required'] });
const checks=[], errors=[];
try {
 const page = await browser.newPage({viewport:{width:1440,height:1100}});
 page.on('pageerror',error=>errors.push(error.message));
 await page.goto(`${process.env.MUSIC_ROOM_URL || 'http://127.0.0.1:5173'}/score.html#rain-letter-v2`);
 await page.waitForFunction(()=>!!window.musicRoom);
 await page.locator('#view-start').fill('9'); await page.locator('#view-start').press('Tab');
 await page.getByRole('button',{name:'选择当前片段'}).click();
 await page.locator('#loop').click();
 await page.locator('#seek').fill('23');
 await page.locator('#mixer summary').click();
 await page.getByRole('button',{name:'独奏主旋律钢琴',exact:true}).click();
 await page.locator('#lead').selectOption('flute');
 await page.locator('.track-level[data-id="melody"]').fill('0.6');
 await page.locator('#volume').fill('0.4');
 const before = await page.evaluate(()=>({view:window.musicRoom.view(),selection:window.musicRoom.selection(),loop:window.musicRoom.engine.loop,position:window.musicRoom.engine.position}));
 assert.equal(before.position,23);
 await page.locator('#compare-start').click();
 assert.deepEqual(await page.evaluate(()=>({id:window.musicRoom.songId,position:window.musicRoom.engine.position,playing:window.musicRoom.engine.playing,solo:window.musicRoom.engine.mix.solo.size,lead:window.musicRoom.engine.mix.lead,level:window.musicRoom.engine.mix.levels.melody,volume:window.musicRoom.engine.mix.volume})),{id:'rain-letter-v2',position:23,playing:false,solo:0,lead:'piano',level:1,volume:.4});
 assert.equal(await page.locator('#lead').isEnabled(),false);
 await page.locator('#compare-b').click();
 assert.equal(await page.evaluate(()=>window.musicRoom.songId),'rain-letter-v1');
 assert.equal(await page.evaluate(()=>window.musicRoom.engine.position),23);
 assert.deepEqual(await page.evaluate(()=>window.musicRoom.engine.loop),before.loop);
 assert.ok(page.url().endsWith('#rain-letter-v2'),'comparison switches must not replace the original version URL');
 checks.push('paused musical position', 'original mix', 'read-only mixer', 'loop mapping', 'comparison URL');
 await page.locator('#play').click(); await page.waitForFunction(()=>window.musicRoom.engine.playing);
 await page.waitForFunction(()=>window.musicRoom.engine.currentTime()>23);
 await page.evaluate(()=>{for(let i=0;i<10;i++){document.querySelector('#compare-a').click();document.querySelector('#compare-b').click();}});
 assert.equal(await page.evaluate(()=>window.musicRoom.songId),'rain-letter-v1');
 assert.equal(await page.evaluate(()=>window.musicRoom.engine.playing),true);
 await page.waitForFunction(()=>window.musicRoom.engine.currentTime()>23);
 assert.ok(await page.evaluate(()=>window.musicRoom.engine.currentTime())>23);
 await page.locator('#volume').fill('0.3');
 await page.locator('#compare-exit').click();
 assert.deepEqual(await page.evaluate(()=>({id:window.musicRoom.songId,position:window.musicRoom.engine.position,playing:window.musicRoom.engine.playing,solo:[...window.musicRoom.engine.mix.solo],lead:window.musicRoom.engine.mix.lead,level:window.musicRoom.engine.mix.levels.melody,volume:window.musicRoom.engine.mix.volume})),{id:'rain-letter-v2',position:23,playing:false,solo:['melody'],lead:'flute',level:.6,volume:.3});
 assert.deepEqual(await page.evaluate(()=>window.musicRoom.view()),before.view);
 assert.deepEqual(await page.evaluate(()=>window.musicRoom.selection()),before.selection);
 assert.equal(await page.locator('#lead').isEnabled(),true);
 checks.push('rapid playing A/B', 'last switch wins', 'exit restores snapshot paused', 'current master volume retained');
 await page.locator('#selection-start').fill('8'); await page.locator('#selection-start').press('Tab');
 assert.equal(await page.locator('#compare-start').isEnabled(),false);
 assert.match(await page.locator('#comparison-reason').textContent(),/跨越段落/);
 await page.locator('#clear-selection').click();
 await page.locator('#compare-start').click();
 await page.locator('#compare-b').click();
 await page.getByRole('button',{name:'选择雨巷来信 第一版',exact:true}).click();
 assert.equal(await page.evaluate(()=>window.musicRoom.comparison()),undefined);
 assert.equal(await page.evaluate(()=>window.musicRoom.engine.position),0);
 await page.goBack(); await page.waitForFunction(()=>window.musicRoom.songId==='rain-letter-v2');
 checks.push('cross-section selection rejected', 'ordinary selection ends comparison', 'back navigation');
 await page.screenshot({path:new URL('desktop.png',output).pathname,fullPage:true});
 await page.setViewportSize({width:390,height:844});
 await page.locator('#compare-start').click(); await page.locator('#compare-b').click(); await page.locator('#compare-exit').click();
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
 checks.push('390px comparison controls');
 assert.deepEqual(errors,[]);
 await writeFile(new URL('verification.json',output),JSON.stringify({checks,errors},null,2));
 console.log(JSON.stringify({checks,errors}));
} finally {await browser.close();}
