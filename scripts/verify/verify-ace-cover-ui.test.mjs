import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm,readFile,writeFile,mkdir} from 'node:fs/promises';
import {existsSync} from 'node:fs';
import {join,resolve} from 'node:path';
import {tmpdir} from 'node:os';
import {chromium,webkit} from 'playwright';
import {MusicService} from '../../src/service/service.ts';
import {serveHttp} from '../../src/server/http.ts';
import {testResources} from '../../src/service/resources/testing.ts';
import {encodeWav} from '../../src/wav.ts';
import {hash} from '../../src/service/projects/store.ts';

test('cover panel selects, loops and submits; grouped comparison keeps time and original and works in both themes',async()=>{
 const root=await mkdtemp(join(tmpdir(),'cover-ui-'));
 const makeWave=(seconds,frequency)=>new Uint8Array(encodeWav([Float32Array.from({length:seconds*48000},(_,i)=>Math.sin(i*frequency)*.2)],48000));
 const original=makeWave(62,.1);
 const read=p=>readFile(resolve('dist',p));
 const music={unsupported:()=>undefined,installed:()=>false,chooseDirectory:async()=>undefined,prepare:async()=>{},launch:async()=>{throw Error('unused');}};
 const speech={installed:()=>false,prepare:async()=>{},generate:async()=>{throw Error('unused');}};
 let received;
 const cover={installed:()=>true,prepare:async()=>{},generate:async(_,request)=>{received=request;return makeWave(request.endSeconds-request.startSeconds,.14);}};
 const open=()=>MusicService.open(root,()=>{throw Error('unused');},read,false,music,speech,undefined,testResources(),undefined,undefined,cover);
 let service=await open(),http,browser;
 try{
  await service.call('create_project',{projectId:'cover-test',title:'把周末铺在湖边'});
  const sound=await service.call('studio_create_sound',{projectId:'cover-test',title:'主题曲',kind:'music'});
  const index=join(root,'studio.json'),data=JSON.parse(await readFile(index,'utf8'));
  data.sounds[0].finalVersionId='v-original';
  data.versions.push({id:'v-original',soundId:sound.id,number:2,createdAt:new Date().toISOString(),state:'succeeded',stage:'已完成',kept:false,deleted:false,duration:62,source:{kind:'audio',id:'v-original'},audioPath:'/studio-audio/v-original',audioHash:hash(original),input:{soundId:sound.id,text:'电子舞曲',lyrics:'原歌词',instrumental:false}});
  await service.close();
  await mkdir(join(root,'studio-audio'));await mkdir(join(root,'lyrics'),{recursive:true});
  await writeFile(join(root,'studio-audio','v-original.wav'),original);
  await writeFile(join(root,'lyrics','v-original.json'),JSON.stringify({format:'music-room-lyrics',version:1,versionId:'v-original',audioPath:'/studio-audio/v-original',audioSha256:hash(original),duration:62,lines:[{start:15,end:19,text:'周六的阳光爬上窗沿'},{start:20,end:22,text:'你把帐篷绑在车后架'}]}));
  await writeFile(index,JSON.stringify(data));
  service=await open();
  http=await serveHttp(service,{read,has:p=>existsSync(resolve('dist',p)),embedded:false});
  browser=process.env.MUSIC_ROOM_BROWSER==='webkit'?await webkit.launch({headless:true}):await chromium.launch({channel:'chrome',headless:true,args:['--autoplay-policy=no-user-gesture-required']});
  const page=await browser.newPage({viewport:{width:1440,height:900},colorScheme:'light'});
  const errors=[];page.on('pageerror',e=>errors.push(e.message));
  await page.goto(http.runtime.url);
  await page.waitForFunction(()=>document.querySelector('#version-audio')?.readyState>=1);
  await page.getByRole('button',{name:'翻唱这段',exact:true}).click();
  await page.locator('#cover-panel').waitFor();
  await page.waitForFunction(()=>document.querySelectorAll(".cover-wave-bars i").length===140);

  assert.equal(await page.locator('[data-action=cover]').getAttribute('aria-pressed'),'true');
  assert.match(await page.locator('[data-action=compose]').innerText(),/再创作一版/);
  await page.waitForFunction(()=>document.querySelector('#cover-form [name=lyrics]')?.value.includes('窗沿'));
  assert.equal(await page.locator('#cover-form [name=start]').inputValue(),'15');
  assert.equal(await page.locator('#cover-form [name=length]').inputValue(),'30');
  await page.locator('[data-handle=start]').press('ArrowRight');
  assert.equal(await page.locator('#cover-form [name=start]').inputValue(),'16');
  const end=await page.locator('[data-handle=end]').boundingBox();
  await page.mouse.move(end.x+end.width/2,end.y+end.height/2);
  await page.mouse.down();
  await page.mouse.move(end.x+end.width/2+25,end.y+end.height/2,{steps:4});
  await page.mouse.up();
  assert.ok(Number(await page.locator('#cover-form [name=length]').inputValue())>29);
  await page.locator('#cover-form [name=start]').fill('15');
  await page.locator('#cover-form [name=length]').fill('20');
  await page.waitForFunction(()=>document.querySelector('[data-cover-selection]')?.textContent.includes('00:35'));
  await page.locator('[data-cover-play]').click();
  await page.waitForFunction(()=>document.querySelector('[data-cover-row-play]')?.getAttribute('aria-label')==='暂停当前版本');
  await page.locator('#version-audio').evaluate(a=>{a.currentTime=34.98;});
  await page.waitForFunction(()=>document.querySelector('#version-audio')?.currentTime<18);
  await page.locator('[data-cover-row-play]').click();
  await page.waitForFunction(()=>document.querySelector('[data-cover-play]')?.getAttribute('aria-label')==='播放');
  await mkdir('test-results/ace-cover-ui',{recursive:true});
  await page.screenshot({path:'test-results/ace-cover-ui/selection-light.png'});
  await page.locator('[data-theme-choice=dark]').click();
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  await page.screenshot({path:'test-results/ace-cover-ui/selection-dark.png'});
  await page.getByRole('button',{name:'生成翻唱新版本'}).click();
  await page.locator('[data-cover-switch=cover]').waitFor();
  await page.waitForFunction(()=>document.querySelector('#version-audio')?.readyState>=1);
  assert.equal(received.startSeconds,15);assert.equal(received.endSeconds,35);
  assert.match(received.lyrics,/阳光爬上窗沿/);
  await page.locator('#version-audio').evaluate(a=>{a.currentTime=12;});
  await page.locator('[data-cover-play]').click();
  await page.locator('[data-cover-switch=original]').click();
  await page.waitForFunction(()=>document.querySelector('[data-cover-switch=original]')?.getAttribute('aria-pressed')==='true');
  const compared=await page.locator('.cover-player audio').evaluate(a=>({seconds:a.currentTime,paused:a.paused}));
  assert.ok(compared.seconds>=26.95&&compared.seconds<28,JSON.stringify(compared));
  assert.equal(compared.paused,false);
  assert.match(await page.locator('[data-cover-right]').innerText(),/对应原曲 00:27/);
  assert.match(await page.locator('.version-row').filter({hasText:'电子舞曲'}).innerText(),/01:02/);
  assert.match(await page.locator('.version-row').filter({hasText:'电子舞曲'}).innerText(),/成品/);
  await page.locator('[data-action=final]').click();
  await page.waitForFunction(()=>document.querySelector('.version-row.selected .tag.final')?.textContent==='成品');
  await page.screenshot({path:'test-results/ace-cover-ui/compare-dark.png'});
  await page.locator('[data-theme-choice=light]').click();
  await page.screenshot({path:'test-results/ace-cover-ui/compare-light.png'});
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-action=cover]').click();
  await page.locator('#cover-panel').waitFor();
  await page.locator('[data-lyric-source]').filter({hasText:'按原歌词顺序估算'}).waitFor();
  assert.match(await page.locator('#cover-form [name=lyrics]').inputValue(),/阳光爬上窗沿/);
  assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth));
  await page.getByRole('button',{name:'关闭翻唱面板'}).click();
  assert.deepEqual(errors,[]);
 }finally{
  await browser?.close();await http?.close();await service.close();await rm(root,{recursive:true,force:true});
 }
});
