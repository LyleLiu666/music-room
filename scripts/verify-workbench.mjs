import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const output = new URL('../test-results/workbench/', import.meta.url);
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args: ['--autoplay-policy=no-user-gesture-required'] });
const checks = [], errors = [];
const url = process.env.MUSIC_ROOM_URL || 'http://127.0.0.1:5173';
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 1100 }, acceptDownloads: true });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(`${url}/#rain-letter-v2`);
  await page.waitForFunction(() => !!window.musicRoom);
  assert.equal(await page.locator('.work-group').count(), 1);
  assert.equal(await page.locator('[data-song]').count(), 2);
  assert.equal(await page.evaluate(() => window.musicRoom.songId), 'rain-letter-v2');
  assert.equal(await page.locator('#mixer').getAttribute('open'), null);
  await page.getByRole('spinbutton', { name: '查看起始小节' }).fill('9');
  await page.getByRole('spinbutton', { name: '查看起始小节' }).press('Tab');
  assert.deepEqual(await page.evaluate(() => window.musicRoom.view()), { startBar: 8, size: 4, follow: false });
  assert.equal(await page.locator('#view-title').textContent(), '第 9—12 小节');
  assert.equal(await page.evaluate(() => window.musicRoom.engine.currentTime()), 0);
  await page.getByRole('combobox', { name: '查看范围' }).selectOption('8');
  assert.equal(await page.locator('#view-title').textContent(), '第 9—16 小节');
  await page.getByRole('spinbutton', { name: '查看起始小节' }).fill('71');
  await page.getByRole('spinbutton', { name: '查看起始小节' }).press('Tab');
  assert.equal(await page.locator('#view-title').textContent(), '第 71—72 小节');
  assert.equal(await page.locator('#chords > div').count(), 2);
  await page.getByRole('button', { name: '副歌 01:20', exact: true }).click();
  assert.equal(await page.evaluate(() => window.musicRoom.engine.position), 80);
  assert.equal(await page.evaluate(() => window.musicRoom.view().startBar), 32);
  checks.push('grouping', 'deep link', '4/8 bar view', 'tail window', 'section navigation');
  await page.locator('#mixer summary').click();
  await page.getByRole('button', { name: '独奏主旋律钢琴', exact: true }).click();
  await page.getByRole('button', { name: '静音贝斯', exact: true }).click();
  await page.getByRole('combobox', { name: '旋律音色' }).selectOption('flute');
  await page.locator('#volume').fill('0.4');
  await page.getByRole('button', { name: '恢复本版默认混音' }).click();
  assert.deepEqual(await page.evaluate(() => ({ solo: window.musicRoom.engine.mix.solo.size, mute: window.musicRoom.engine.mix.muted.size, lead: window.musicRoom.engine.mix.lead, volume: window.musicRoom.engine.mix.volume })), { solo: 0, mute: 0, lead: 'piano', volume: .4 });
  await page.locator('#play').click();
  await page.waitForFunction(() => window.musicRoom.engine.playing);
  await page.waitForTimeout(300);
  assert.ok(await page.evaluate(() => window.musicRoom.engine.currentTime()) > 80);
  await page.getByRole('button', { name: '选择雨巷来信 第一版', exact: true }).click();
  assert.deepEqual(await page.evaluate(() => ({ id: window.musicRoom.songId, position: window.musicRoom.engine.position, playing: window.musicRoom.engine.playing, volume: window.musicRoom.engine.mix.volume })), { id: 'rain-letter-v1', position: 0, playing: false, volume: .4 });
  await page.goBack();
  await page.waitForFunction(() => window.musicRoom.songId === 'rain-letter-v2');
  await page.goForward();
  await page.waitForFunction(() => window.musicRoom.songId === 'rain-letter-v1');
  await page.reload();
  await page.waitForFunction(() => !!window.musicRoom);
  assert.equal(await page.evaluate(() => window.musicRoom.engine.playing), false);
  checks.push('default mix restoration', 'master volume retained', 'real playback', 'switch stops old audio', 'back/forward', 'reload paused');
  await page.goto(`${url}/#unknown-version`);
  await page.waitForFunction(() => !!window.musicRoom);
  assert.equal(await page.evaluate(() => window.musicRoom.songId), 'rain-letter-v1');
  assert.match(await page.locator('#status').textContent(), /未找到该版本/);
  const event = page.waitForEvent('download');
  await page.getByRole('button', { name: 'MIDI', exact: true }).click();
  assert.equal((await event).suggestedFilename(), 'rain-letter-v1.mid');
  await page.screenshot({ path: new URL('desktop.png', output).pathname, fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  await page.getByRole('button', { name: '作品库', exact: true }).click();
  await page.getByRole('button', { name: '选择雨巷来信 第二版 · Riff', exact: true }).click();
  await page.getByRole('button', { name: '作品库', exact: true }).click();
  await page.getByRole('spinbutton', { name: '查看起始小节' }).fill('9');
  await page.getByRole('spinbutton', { name: '查看起始小节' }).press('Tab');
  assert.equal(await page.locator('#view-title').textContent(), '第 9—12 小节');
  await page.screenshot({ path: new URL('mobile.png', output).pathname, fullPage: true });
  await page.getByRole('button', { name: '选择当前片段' }).click();
  assert.deepEqual(await page.evaluate(() => window.musicRoom.selection()), { startBeat: 32, endBeat: 48 });
  await page.getByRole('button', { name: '循环此片段', exact: true }).click();
  assert.equal(await page.evaluate(() => window.musicRoom.engine.position), 20);
  assert.equal(await page.evaluate(() => window.musicRoom.engine.playing), false);
  await page.locator('#play').click();
  await page.waitForFunction(() => window.musicRoom.engine.playing);
  await page.waitForFunction(() => window.musicRoom.engine.currentTime() > 20);
  await page.locator('#play').click();
  const paused = await page.evaluate(() => window.musicRoom.engine.position);
  assert.ok(paused > 20 && paused < 30);
  assert.ok(await page.evaluate(() => !!window.musicRoom.engine.loop));
  await page.getByRole('spinbutton', { name: '选区起始小节' }).fill('12');
  await page.getByRole('spinbutton', { name: '选区起始小节' }).press('Tab');
  assert.deepEqual(await page.evaluate(() => window.musicRoom.selection()), { startBeat: 44, endBeat: 48 });
  assert.equal(await page.evaluate(() => window.musicRoom.engine.position), 27.5);
  await page.getByRole('button', { name: '副歌 01:20', exact: true }).click();
  assert.equal(await page.evaluate(() => window.musicRoom.engine.loop), undefined);
  assert.equal(await page.evaluate(() => window.musicRoom.engine.position), 80);
  await page.getByRole('button', { name: '清除选择' }).click();
  assert.equal(await page.getByRole('button', { name: '循环此片段', exact: true }).isEnabled(), false);
  checks.push('whole-bar selection', 'paused loop enable', 'pause preserves loop', 'loop range change', 'outside seek disables loop', 'clear selection');
  checks.push('invalid address fallback', 'independent MIDI', '390px layout and controls');
  assert.deepEqual(errors, []);
  await writeFile(new URL('verification.json', output), JSON.stringify({ checks, errors }, null, 2));
  console.log(JSON.stringify({ checks, errors }));
} finally { await browser.close(); }
