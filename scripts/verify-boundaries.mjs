import { chromium } from 'playwright';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const output=new URL('../test-results/boundaries/',import.meta.url); await mkdir(output,{recursive:true});
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--autoplay-policy=no-user-gesture-required']});
const checks=[],errors=[];
const url=process.env.MUSIC_ROOM_URL||'http://127.0.0.1:5173';
try {
 const page=await browser.newPage(); page.on('pageerror',e=>errors.push(e.message));
 await page.route('**/samples/piano-C2.mp3',async route=>{await new Promise(resolve=>setTimeout(resolve,50));await route.fulfill({status:503,body:'fixture failure'});});
 await page.goto(`${url}/score.html#rain-letter-v2`); await page.waitForFunction(()=>!!window.musicRoom);
 await page.locator('#play').click();
 await page.waitForFunction(()=>document.querySelector('#status').textContent.startsWith('播放失败'));
 await page.waitForTimeout(400);
 assert.match(await page.locator('#status').textContent(),/^播放失败/,'late successful sample jobs must not overwrite the error');
 await page.unroute('**/samples/piano-C2.mp3');
 await page.locator('#play').click(); await page.waitForFunction(()=>window.musicRoom.engine.playing);
 await page.locator('#play').click();
 checks.push('sample failure remains visible', 'retry after failure');
 const loading=await browser.newPage(); loading.on('pageerror',e=>errors.push(e.message));
 await loading.route('**/samples/**',async route=>{await new Promise(resolve=>setTimeout(resolve,300));await route.continue();});
 await loading.goto(`${url}/score.html#rain-letter-v2`); await loading.waitForFunction(()=>!!window.musicRoom);
 await loading.locator('#play').click();
 await loading.getByRole('button',{name:'选择雨巷来信 第一版',exact:true}).click();
 await loading.waitForFunction(()=>window.musicRoom.engine.ready);
 assert.equal(await loading.evaluate(()=>window.musicRoom.engine.playing),false);
 assert.equal(await loading.evaluate(()=>window.musicRoom.songId),'rain-letter-v1');
 await loading.locator('#play').click(); await loading.waitForFunction(()=>window.musicRoom.engine.playing);
 await loading.locator('#play').click();
 checks.push('pending version switch cancels old playback', 'cached samples playable after switch');
 await page.locator('#view-start').fill('9'); await page.locator('#view-start').press('Tab');
 await page.locator('#select-drag').click();
 const canvas=page.locator('[data-lane="melody"]'); await canvas.scrollIntoViewIfNeeded(); const rect=await canvas.boundingBox();
 await page.mouse.move(rect.x+rect.width*.8,rect.y+20);await page.mouse.down();await page.mouse.move(rect.x+rect.width*.05,rect.y+20);await page.mouse.up();
 assert.deepEqual(await page.evaluate(()=>window.musicRoom.selection()),{startBeat:32,endBeat:48});
 await page.locator('#selection-end').fill('73');await page.locator('#selection-end').press('Tab');
 assert.deepEqual(await page.evaluate(()=>window.musicRoom.selection()),{startBeat:32,endBeat:48});
 assert.equal(await page.locator('#selection-end').inputValue(),'12');
 checks.push('reverse drag normalization', 'invalid entry restores valid range');
 await page.locator('#follow').click();
 await page.evaluate(()=>{const e=window.musicRoom.engine;e.seek(29.9);e.play();});
 await page.waitForFunction(()=>window.musicRoom.view().startBar===12);
 await page.evaluate(()=>window.musicRoom.engine.pause());
 checks.push('automatic local window follows playback');
 await page.locator('#mixer summary').focus();await page.keyboard.press('Space');
 assert.equal(await page.evaluate(()=>window.musicRoom.engine.playing),false);
 assert.equal(await page.locator('#mixer').getAttribute('open'),'');
 await page.getByRole('button',{name:'独奏主旋律钢琴',exact:true}).click();
 await page.getByRole('button',{name:'静音主旋律钢琴',exact:true}).click();
 await page.evaluate(()=>window.musicRoom.engine.play(80));await page.waitForTimeout(140);
 const gains=await page.evaluate(()=>({melody:window.musicRoom.engine.graph.buses.get('melody').gain.value,other:window.musicRoom.engine.graph.buses.get('piano').gain.value}));
 assert.ok(gains.melody<.001&&gains.other<.001);
 await page.evaluate(()=>window.musicRoom.engine.pause());
 checks.push('summary keyboard does not start music', 'mute takes priority over solo in audio routing');
 assert.deepEqual(errors,[]);await writeFile(new URL('verification.json',output),JSON.stringify({checks,errors},null,2));console.log(JSON.stringify({checks,errors}));
} finally {await browser.close();}
