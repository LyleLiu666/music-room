import test from 'node:test';
import assert from 'node:assert/strict';
import {mkdtemp,rm} from 'node:fs/promises';
import {tmpdir} from 'node:os';
import {join} from 'node:path';
import {MusicService} from '../service/service.ts';
import {testResources} from '../service/resources/testing.ts';
import {serveHttp} from './http.ts';
import {WorkbenchService} from '../workbench/service.ts';
test('an existing client survives a real HTTP service restart; session keeps origin and cache protections',async t=>{
 const root=await mkdtemp(join(tmpdir(),'session-recovery-'));
 const assets={read:async()=>new TextEncoder().encode('<html><head></head></html>'),has:()=>true,embedded:false};
 const service=await MusicService.open(root,()=>{throw Error('unused');},assets.read,false,undefined,undefined,undefined,testResources());
 let http=await serveHttp(service,assets);
 t.after(async()=>{await http.close();await service.close();await rm(root,{recursive:true,force:true});});
 const base=http.runtime.url,old=http.runtime.token,originalFetch=globalThis.fetch;
 const nativeFetch=(url:string|URL,init:RequestInit={})=>{const headers=new Headers(init.headers);headers.set('connection','close');return originalFetch(url,{...init,headers});};
 const first=await nativeFetch(base+'/local-session');assert.equal(first.status,200);assert.equal(first.headers.get('cache-control'),'no-store');
 const api=new WorkbenchService(await first.json());
 assert.equal((await nativeFetch(base+'/local-session',{headers:{origin:'https://evil.invalid'}})).status,403);
 assert.equal((await nativeFetch(base+'/local-session',{method:'POST'})).status,405);
 await http.close();http=await serveHttp(service,assets,Number(new URL(base).port));
 assert.notEqual(http.runtime.token,old);
 t.mock.method(globalThis,'fetch',(path:string,init?:RequestInit)=>nativeFetch(new URL(path,base),init));
 await api.call('create_project',{projectId:'recovered',title:'恢复后创建'});
 const result=await api.call('list_projects',{});assert.equal(result.projects.length,1);
 assert.equal(api.bootstrap.token,http.runtime.token);
 assert.equal((await nativeFetch(base+'/api/list_projects',{method:'POST',headers:{authorization:'Bearer '+old}})).status,401);
});
